/// <summary>
/// Состояние взаимодействия игрока с болотом. Одно свойство вместо набора флагов.
/// Инвариант: SwampPhase != None ⇔ игрок «в болоте» (болото видно, кнопки заблокированы).
/// </summary>
public enum SwampPhase
{
    /// <summary>Игрок не в болоте.</summary>
    None,

    /// <summary>Попал в болото. Ждём Ход 2 — показ пропуска.</summary>
    SkipPending,

    /// <summary>Пропуск показан (Ход 2). Ждём Ход 3 — сброс и применение отложенных эффектов.</summary>
    AwaitingEffects
}